export const trOffer = (s: string | undefined, lang: string): string => {
  if (!s) return '';
  if (lang === 'es') return s;
  // Handle "S/ 389 por noche"
  if (s.endsWith(' por noche')) {
    const base = s.replace(' por noche', '');
    return lang === 'zh' ? `${base} 起 / 每晚` : `${base} per night`;
  }
  const hit = OFFER_UI[s];
  return hit ? (lang === 'zh' ? hit.zh : hit.en) : s;
};
